"""
train_model.py — Demand prediction model for the Food Waste AI Assistant.

NOTE: This script trains on SIMULATED data generated by generate_data.py.
The target variable (meals_consumed) is itself derived from simulated
consumption patterns, so all reported metrics reflect prototype-only
performance on synthetic data.  They are NOT indicative of real-world
prediction accuracy and should not be used as operational benchmarks
without validation against genuine canteen records.

Run order:
  1. python generate_data.py
  2. python train_model.py
"""

import datetime
import json
import os
import sys

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.compose import ColumnTransformer
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler


# --------------------------------------------------
# Constants
# --------------------------------------------------
DATA_PATH  = "data/canteen_data.csv"
MODEL_PATH = "model/demand_model.pkl"
META_PATH  = "model/model_metadata.json"

FEATURES           = ["day_of_week", "menu_type", "students_expected"]
CATEGORICAL_FEATS  = ["day_of_week", "menu_type"]
NUMERIC_FEATS      = ["students_expected"]
TARGET             = "meals_consumed"

TRAIN_RATIO = 0.8   # chronological split — first 80% of rows train, last 20% test


# --------------------------------------------------
# Entry point
# --------------------------------------------------
if __name__ == "__main__":

    # --------------------------------------------------
    # 1. Guard: confirm data file exists
    # --------------------------------------------------
    if not os.path.exists(DATA_PATH):
        sys.exit(
            f"Error: '{DATA_PATH}' not found. "
            "Please run generate_data.py first."
        )

    # --------------------------------------------------
    # 2. Load dataset
    # --------------------------------------------------
    df = pd.read_csv(DATA_PATH, parse_dates=["date"])

    # Sort by date to ensure chronological ordering before splitting.
    df = df.sort_values("date").reset_index(drop=True)

    X = df[FEATURES]
    y = df[TARGET]

    # --------------------------------------------------
    # 3. Chronological 80/20 split
    #    Rows are sorted by date so training data is always
    #    earlier than test data — as it would be in production.
    # --------------------------------------------------
    split_idx = int(len(df) * TRAIN_RATIO)

    X_train, X_test = X.iloc[:split_idx], X.iloc[split_idx:]
    y_train, y_test = y.iloc[:split_idx], y.iloc[split_idx:]

    print(f"Dataset rows   : {len(df)}")
    print(f"Training rows  : {len(X_train)}  "
          f"({df['date'].iloc[0].date()} to {df['date'].iloc[split_idx - 1].date()})")
    print(f"Test rows      : {len(X_test)}  "
          f"({df['date'].iloc[split_idx].date()} to {df['date'].iloc[-1].date()})")

    # --------------------------------------------------
    # 4. Preprocessing
    # --------------------------------------------------
    preprocessor = ColumnTransformer(
        transformers=[
            (
                "categorical",
                OneHotEncoder(handle_unknown="ignore"),
                CATEGORICAL_FEATS,
            ),
            (
                "numeric",
                StandardScaler(),
                NUMERIC_FEATS,
            ),
        ]
    )

    # --------------------------------------------------
    # 5. Model  (RandomForest kept unchanged per requirements)
    # --------------------------------------------------
    model = RandomForestRegressor(n_estimators=200, random_state=42)

    pipeline = Pipeline(
        steps=[
            ("preprocessor", preprocessor),
            ("model",         model),
        ]
    )

    # --------------------------------------------------
    # 6. Train
    # --------------------------------------------------
    pipeline.fit(X_train, y_train)
    print("\nModel trained successfully!")

    # --------------------------------------------------
    # 7. Evaluate
    # --------------------------------------------------
    predictions = pipeline.predict(X_test)

    mae      = mean_absolute_error(y_test, predictions)
    rmse     = np.sqrt(mean_squared_error(y_test, predictions))
    r2       = r2_score(y_test, predictions)
    bias     = float(np.mean(predictions - y_test))

    # Simple baseline: predict the training-set mean for every test row.
    baseline_pred = np.full(len(y_test), y_train.mean())
    baseline_mae  = mean_absolute_error(y_test, baseline_pred)

    print("\n--- Evaluation (prototype / simulated data only) ---")
    print(f"  MAE          : {mae:.2f} meals")
    print(f"  RMSE         : {rmse:.2f} meals")
    print(f"  R\u00b2           : {r2:.4f}")
    print(f"  Mean bias    : {bias:+.2f} meals  "
          "(positive = over-predicts, negative = under-predicts)")
    print(f"  Baseline MAE : {baseline_mae:.2f} meals  (mean-of-training predictor)")
    print("----------------------------------------------------")
    print(
        "\nNOTE: These metrics reflect simulated data where meals_consumed "
        "is derived from simulated consumption patterns. "
        "They are NOT real-world performance indicators."
    )

    # --------------------------------------------------
    # 8. Save model
    # --------------------------------------------------
    os.makedirs(os.path.dirname(MODEL_PATH), exist_ok=True)
    joblib.dump(pipeline, MODEL_PATH)
    print(f"\nModel saved to {MODEL_PATH}")

    # --------------------------------------------------
    # 9. Save metadata
    # --------------------------------------------------
    metadata = {
        "trained_at":        datetime.datetime.now().isoformat(),
        "scikit_learn_version": sklearn.__version__,
        "data_source":       DATA_PATH,
        "note":              (
            "Trained on SIMULATED data. Metrics are prototype-only "
            "and do not represent real-world canteen performance."
        ),
        "split_type":        "chronological",
        "train_rows":        len(X_train),
        "test_rows":         len(X_test),
        "train_date_range":  (
            f"{df['date'].iloc[0].date()} to "
            f"{df['date'].iloc[split_idx - 1].date()}"
        ),
        "test_date_range":   (
            f"{df['date'].iloc[split_idx].date()} to "
            f"{df['date'].iloc[-1].date()}"
        ),
        "features":          FEATURES,
        "categorical_features": CATEGORICAL_FEATS,
        "numeric_features":  NUMERIC_FEATS,
        "target":            TARGET,
        "n_estimators":      200,
        "metrics": {
            "mae":          round(mae,  2),
            "rmse":         round(rmse, 2),
            "r2":           round(r2,   4),
            "mean_bias":    round(bias, 2),
            "baseline_mae": round(baseline_mae, 2),
        },
    }

    os.makedirs(os.path.dirname(META_PATH), exist_ok=True)
    with open(META_PATH, "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)

    print(f"Metadata saved to {META_PATH}")
